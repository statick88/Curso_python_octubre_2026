# int y str convierten valores entre texto y números.
print(2 + int("2"))
print(str(2) + " edades")

print("Hello \t world")  # \t inserta una tabulación.
print("primera linea \nsegunda linea")  # \n inicia una nueva línea.

# Una cadena cruda conserva las barras invertidas.
print(r"c:\nombre\repositorio")
